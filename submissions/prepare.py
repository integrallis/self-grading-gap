#!/usr/bin/env python3
"""Extract shared manuscript inputs; leave the reviewed paper untouched."""

import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PAPER = ROOT.parent / "paper"
SHARED = ROOT / "_shared"


def layout(text):
    # IEEE's default description label width overlaps these long RQ labels.
    text = text.replace(r"\begin{description}", "")
    text = text.replace(r"\end{description}", "")
    text = re.sub(r"\\item\[(\\textbf\{RQ[^\n]+?\})\]", r"\n\\noindent\1", text)
    # Wide source tables and diagrams need both IEEE columns, not smaller fonts.
    text = re.sub(r"\\begin\{(table|figure)\}\[[^]]*\]", r"\\begin{\1*}[t]", text)
    text = re.sub(r"\\end\{(table|figure)\}", r"\\end{\1*}", text)
    # IEEE conference papers use figures for pseudocode rather than a separate
    # algorithm float; preserve algorithm labels and the actual pseudocode.
    text = re.sub(r"\\begin\{algorithm\}\[[^]]*\]", r"\\begin{figure*}[t]", text)
    text = text.replace(r"\end{algorithm}", r"\end{figure*}")
    text = re.sub(r"Algorithm~(\\ref\{alg:[^}]+\})", r"Figure~\1", text)
    text = text.replace(r"\begin{tabular}{lll}", r"\begin{tabularx}{\textwidth}{lXl}")
    # Only the defect-register table uses three left-aligned columns.
    if r"\begin{tabularx}" in text:
        start = text.index(r"\begin{tabularx}")
        end = text.index(r"\end{tabular}", start)
        text = text[:end] + text[end:].replace(r"\end{tabular}", r"\end{tabularx}", 1)
    text = text.replace(r"\begin{verbatim}", r"\begin{Verbatim}[breaklines,breakanywhere]")
    text = text.replace(r"\end{verbatim}", r"\end{Verbatim}")
    return text


def main():
    source = (PAPER / "main.tex").read_text()
    abstract = source.split(r"\begin{abstract}", 1)[1].split(r"\end{abstract}", 1)[0]
    body = source[source.index(r"\section{Introduction}"):source.index(r"\bibliographystyle")]
    appendices = source.split(r"\appendix", 1)[1].split(r"\end{document}", 1)[0]
    SHARED.mkdir(exist_ok=True)
    banner = "% Generated by submissions/prepare.py from paper/main.tex; edit the source, not this file.\n"
    (SHARED / "abstract.tex").write_text(banner + abstract.strip() + "\n")
    (SHARED / "full-body.tex").write_text(banner + layout(body))
    (SHARED / "appendices.tex").write_text(banner + layout(appendices))
    inputs = [PAPER / "main.tex", PAPER / "refs.bib", PAPER / "audit_numbers.tex"]
    inputs += [PAPER / p for p in re.findall(r"\\includegraphics\[[^]]*\]\{([^}]+)\}", source)]
    manifest = {"source": "paper/main.tex", "scientific_content": "reviewed preprint; no new experiments",
                "inputs_sha256": {str(p.relative_to(ROOT.parent)): hashlib.sha256(p.read_bytes()).hexdigest()
                                  for p in inputs}}
    (SHARED / "source-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print("Extracted shared abstract, full manuscript, and appendices from paper/main.tex.")


if __name__ == "__main__":
    main()
