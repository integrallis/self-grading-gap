def render_lcd_digit(number):
    lcd_segments = {
        '0': ['._.', '|.|', '|_|'],
        '1': ['...', '..|', '..|'],
        '2': ['._.', '._|', '|_.'],
        '3': ['._.', '._|', '._|'],
        '4': ['...', '|_|', '..|'],
        '5': ['._.', '|_.', '._|'],
        '6': ['._.', '|_.', '|_|'],
        '7': ['._.', '..|', '..|'],
        '8': ['._.', '|_|', '|_|'],
        '9': ['._.', '|_|', '._|']
    }
    rows = ['', '', '']
    for digit in str(number):
        segments = lcd_segments[digit]
        for i in range(3):
            rows[i] += segments[i]
    return '\n'.join(rows) + '\n'