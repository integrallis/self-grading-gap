def render_digit(digit):
    segments = {
        '0': ['._.', '|.|', '|_|'],
        '1': ['...', '..|', '..|'],
        '2': ['._.', '._|', '|_.'],
        '3': ['._.', '._|', '._|'],
        '4': ['...', '|_|', '..|'],
        '5': ['._.', '|_.', '._|'],
        '6': ['._.', '|_.', '|_|'],
        '7': ['._.', '..|', '..|'],
        '8': ['._.', '|_|', '|_|'],
        '9': ['._.', '|_|', '..|']
    }

    result = ['' for _ in range(3)]
    for digit_char in str(digit):
        for i in range(3):
            result[i] += segments[digit_char][i]
    return '\n'.join(result) + '\n'