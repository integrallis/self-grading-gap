def function_name(digit):
    lcd_digits = {
        '0': ["._.", "|.|", "|_|"],
        '1': ["...", "..|", "..|"],
        '2': ["._.", "._|", "|_."],
        '3': ["._.", "._|", "._|"],
        '4': ["...", "|_|", "..|"],
        '5': ["._.", "|_.", "._|"],
        '6': ["._.", "|_.", "|_|"],
        '7': ["._.", "..|", "..|"],
        '8': ["._.", "|_|", "|_|"],
        '9': ["._.", "|_|", "..|"],
    }

    digit_str = str(digit)
    lines = ["", "", ""]

    for char in digit_str:
        for i in range(3):
            lines[i] += lcd_digits[char][i]

    return '\n'.join(lines) + '\n'